def run_tool_agent(agent_name, system_prompt, question, context, task, tools):

    functions = {function.__name__: function for function in tools}
    forward = is_forward_looking(question)

    user_prompt = build_user_prompt(question, context, task)

    messages = [
        {"role": "system", "content": system_prompt + COMMON_RULES},
        {"role": "user", "content": user_prompt},
    ]

    seen = {}
    stalled = 0
    final_text = None

    for iteration in range(1, MAX_ITERATIONS + 1):

        response = chat(messages, tools)
        message = response.message
        messages.append(message)

        calls = message.tool_calls or []

        RUN_LOG["iterations"].append({
            "agent": agent_name,
            "iteration": iteration,
            "tool_calls": [c.function.name for c in calls],
            "text_length": len(message.content or ""),
        })

        if not calls:
            final_text = message.content or ""
            break

        progress = False

        for call in calls:

            name = call.function.name
            arguments = dict(call.function.arguments or {})
            key = name + json.dumps(arguments, sort_keys=True, default=str)

            print(f"[{agent_name}] tool {name} {arguments}")

            if key in seen:
                result = {
                    "status": "error",
                    "error": (
                        "DUPLICATE_CALL: this exact call was already "
                        "executed; its result is earlier in the conversation. "
                        "Do not repeat it. Write the final report now."
                    ),
                }
                status = "duplicate_blocked"

            else:
                result = _execute(name, arguments, functions)
                seen[key] = result
                status = result["status"]

                if status == "ok":
                    progress = True

            print(f"[{agent_name}] -> {status}")

            RUN_LOG["tool_calls"].append({
                "agent": agent_name,
                "tool": name,
                "arguments": arguments,
                "status": status,
                "result": result,
            })

            messages.append({
                "role": "tool",
                "tool_name": name,
                "content": json.dumps(result, default=str),
            })

        stalled = 0 if progress else stalled + 1

        if stalled >= MAX_STALLED_ROUNDS:
            RUN_LOG["warnings"].append(
                f"[{agent_name}] stalled: {stalled} rounds without a new "
                f"successful tool call; tools closed."
            )
            break

    if final_text is None:

        RUN_LOG["warnings"].append(
            f"[{agent_name}] tool budget closed; final report was forced."
        )

        messages.append({
            "role": "user",
            "content": (
                "Tool use is now CLOSED. Write your final report using only "
                "the ledger, the successful tool results and the evidence. "
                "List failed or impossible calculations under Missing "
                "Information. Do not write code. Do not call tools."
            ),
        })

        response = chat(messages, None)
        final_text = response.message.content or ""
        messages.append({"role": "assistant", "content": final_text})

    allowed = build_allowed_numbers(user_prompt)

    final_text, violations = repair_until_valid(
        messages, final_text, allowed, forward
    )

    if not final_text.strip():
        final_text = "(The agent returned no report.)"

    if violations:
        for violation in violations:
            RUN_LOG["warnings"].append(f"[{agent_name}] {violation}")

        final_text = (
            "[VALIDATION FAILED - claims below are NOT verified; "
            "see audit]\n\n" + final_text
        )

    return final_text + AUDIT_MARKER + "\n" + format_tool_audit(agent_name)