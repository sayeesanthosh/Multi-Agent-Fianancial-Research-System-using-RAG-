COMMON_RULES = """

TOOL AND EVIDENCE RULES (apply to every answer):
1. The VERIFIED FACT LEDGER in the user message is the only source of
   reported financial figures for calculations. Calculation tools take a
   fiscal year or a metric name, never raw numbers. Tools read the ledger.
2. If a tool returns status "error", that calculation FAILED. Report it as
   failed and name the missing input. Never replace a failed result with
   your own figure, estimate or code.
3. Never write Python, pandas or any code. Never use the words "assume",
   "suppose" or "hypothetical" to create figures.
4. Never call the same tool with the same arguments twice.
5. Quote a figure only if it is in the ledger, in a successful tool result,
   or in the retrieved evidence (cite source and page).
6. Historical results are not forecasts. Never present a past margin or
   growth rate as a prediction of a future period.
7. Label statements: [Verified fact] [Calculated] [Interpretation]
   [Assumption] [Unsupported].
8. Metric meanings: net_sales is revenue. total_current_assets,
   total_current_liabilities, total_liabilities and operating_cash_flow are
   NOT revenue. Total liabilities and current liabilities are NOT total debt.
9. When finished, write the report as plain text without further tool calls.
"""

FORWARD_NOTICE = """FORWARD-LOOKING QUESTION:
This question concerns a future period. The documents are historical.
Separate: (1) historical profitability, (2) current financial condition,
(3) management guidance, (4) forward-looking market expectations,
(5) scenario projections, (6) uncertainty and missing information.
Do not predict the future from past margins. If guidance or forward-looking
evidence is not in the retrieved passages, say it is unavailable."""

FORWARD_LIMITATION = (
    "The question concerns a future period, but the verified evidence is "
    "historical reported results. Unless the retrieved passages explicitly "
    "contain management guidance (see the Research Analyst's evidence), no "
    "guidance, analyst expectation or projection was identified. This report "
    "therefore makes no prediction of next-year profitability. Historical "
    "margins describe past performance only."
)

FORWARD_PATTERN = re.compile(
    r"\b(next\s+(year|quarter|fiscal\s+year)|will\b|going\s+to|forecast|"
    r"predict|projection|outlook|expect(ed|ations)?|future|upcoming|"
    r"guidance|fy\s?20(2[6-9]|3\d))",
    re.IGNORECASE,
)


def is_forward_looking(question):
    return bool(FORWARD_PATTERN.search(question or ""))


def ledger_block():
    ledger = fact_ledger.get_active_ledger()

    if ledger is None or not ledger.facts:
        return (
            "VERIFIED FACT LEDGER: EMPTY. No ratio may be calculated. "
            "Report every financial input as missing."
        )

    warnings = "\n".join(f"- {w}" for w in ledger.warnings)

    return (
        "VERIFIED FACT LEDGER (authoritative; fact_id = metric_fiscalyear):\n"
        f"{ledger.as_table()}\n\nLEDGER WARNINGS:\n{warnings}"
    )


def build_user_prompt(question, context, task):
    parts = [f"Research question:\n{question}"]

    if is_forward_looking(question):
        parts.append(FORWARD_NOTICE)

    parts.append(ledger_block())
    parts.append(f"Retrieved evidence and user-supplied context:\n{context}")
    parts.append(task)

    return "\n\n".join(parts)


def report_body(report):
    return report.split(AUDIT_MARKER)[0]


