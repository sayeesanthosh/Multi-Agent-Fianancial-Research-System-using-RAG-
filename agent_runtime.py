# VALIDATION
# ==========================================

_NUM = re.compile(r"\d[\d,]*(?:\.\d+)?")

MISLABEL_RULES = {
    "total_current_assets": ("revenue", "net sales", "total sales"),
    "total_assets": ("revenue", "net sales", "total sales"),
    "operating_cash_flow": ("revenue", "net sales", "total sales",
                            "net income", "net profit"),
    "total_current_liabilities": ("total debt", "debt of", "debt was", "debt is"),
    "total_liabilities": ("total debt", "debt of", "debt was", "debt is"),
}


def _numbers_in(text):
    values = []

    for token in _NUM.findall(text or ""):
        try:
            values.append(float(token.replace(",", "")))
        except ValueError:
            pass

    return values


def build_allowed_numbers(context_text):
    allowed = set(_numbers_in(context_text))
    ledger = fact_ledger.get_active_ledger()

    if ledger:
        for fact in ledger.facts.values():
            allowed.add(float(fact["value"]))

    for call in RUN_LOG["tool_calls"]:
        if call["status"] == "ok":
            allowed.update(_numbers_in(json.dumps(call["result"], default=str)))

    return allowed


def _pct_allowed(token, allowed):
    decimals = len(token.split(".")[1]) if "." in token else 0
    tolerance = 0.5 * 10 ** (-decimals) + 0.005
    target = abs(float(token))

    return any(abs(abs(a) - target) <= tolerance for a in allowed)


def _mislabel_violations(text):
    ledger = fact_ledger.get_active_ledger()
    found = set()

    if ledger is None:
        return []

    for fact in ledger.facts.values():

        words = MISLABEL_RULES.get(fact["metric"])

        if not words:
            continue

        value = int(round(fact["value"]))

        for token in {f"{value:,}", str(value)}:
            for match in re.finditer(re.escape(token), text):

                segment = text[max(0, match.start() - 40):match.start()]
                segment = re.split(r"[;,\n()]|\band\b", segment)[-1].lower()

                for word in words:
                    if word in segment:
                        found.add(
                            f"Figure {token} is ledger metric "
                            f"'{fact['metric']}' but is described near "
                            f"'{word}'. Wrong metric mapping."
                        )

    return sorted(found)


def validate_report(text, allowed, forward_looking=False):
    violations = []

    if re.search(r"```|\bimport\s+pandas\b|\bpd\.\w+|\bDataFrame\b", text):
        violations.append(
            "Contains code. Do not write code; use only the registered tools."
        )

    if re.search(r"let'?s assume|\bsuppose\b|hypothetical", text, re.IGNORECASE):
        violations.append("Uses hypothetical or assumed figures.")

    unsupported = set()

    for match in _NUM.finditer(text):
        token = match.group(0).rstrip(",")

        try:
            value = float(token.replace(",", ""))
        except ValueError:
            continue

        digits = len(token.replace(",", "").split(".")[0])

        if digits >= 5 and value not in allowed:
            unsupported.add(token)

    if unsupported:
        violations.append(
            "Figures not found in the ledger, tool results or evidence: "
            f"{sorted(unsupported)}."
        )

    bad_pct = set()

    for match in re.finditer(r"(-?\d+(?:\.\d+)?)\s*%", text):
        if not _pct_allowed(match.group(1), allowed):
            bad_pct.add(match.group(1) + "%")

    if bad_pct:
        violations.append(
            "Percentages not backed by a successful tool result or evidence: "
            f"{sorted(bad_pct)}."
        )

    violations.extend(_mislabel_violations(text))

    if forward_looking and re.search(
        r"\b(will|is expected to|is likely to|should)\s+"
        r"(be|remain|stay|continue to be)\s+profitable",
        text, re.IGNORECASE,
    ):
        violations.append(
            "States a future-profitability prediction not supported by "
            "forward-looking evidence."
        )

    return violations


def repair_until_valid(messages, text, allowed, forward_looking=False,
                       num_ctx=NUM_CTX):
    violations = []

    for attempt in range(MAX_REPAIRS + 1):

        violations = validate_report(text, allowed, forward_looking)

        if not violations or attempt == MAX_REPAIRS:
            break

        messages.append({
            "role": "user",
            "content": (
                "Your report was REJECTED for these reasons:\n- "
                + "\n- ".join(violations)
                + "\n\nRewrite the full report. Use only ledger facts, "
                  "successful tool results and cited evidence. List failed "
                  "or impossible calculations under Missing Information. "
                  "Do not write code. Do not call tools."
            ),
        })

        response = chat(messages, None, num_ctx)
        text = response.message.content or ""
        messages.append({"role": "assistant", "content": text})

    return text, violations


