def _execute(name, arguments, functions):
    function = functions.get(name)

    if function is None:
        return {
            "status": "error",
            "error": f"Unknown tool '{name}'. Available: {sorted(functions)}",
        }

    try:
        result = function(**arguments)

    except TypeError as error:
        return {
            "status": "error",
            "error": (
                f"Invalid arguments for {name}: {error}. "
                f"Expected signature: {name}{inspect.signature(function)}"
            ),
        }

    except Exception as error:
        return {"status": "error", "error": f"{type(error).__name__}: {error}"}

    if not isinstance(result, dict):
        result = {"status": "ok", "value": result}

    result.setdefault("status", "ok")

    return result


def format_tool_audit(agent=None):
    calls = [c for c in RUN_LOG["tool_calls"] if agent in (None, c["agent"])]

    ok, failed, blocked = [], [], []

    for call in calls:

        args = ", ".join(f"{k}={v}" for k, v in call["arguments"].items())
        head = f"{call['agent']}: {call['tool']}({args})"

        if call["status"] == "ok":
            result = call["result"]

            if "value" in result:
                inputs = "; ".join(
                    f"{i['fact_id']}={i['value']:,.0f} (pdf p.{i['pdf_page']})"
                    for i in result.get("inputs", [])
                )
                ok.append(
                    f"- {head} = {result['value']} {result.get('unit', '')} "
                    f"| {result.get('formula', '')} | inputs: {inputs}"
                )
            else:
                ok.append(f"- {head} -> ok")

        elif call["status"] == "duplicate_blocked":
            blocked.append(f"- {head}")

        else:
            failed.append(f"- {head} -> {call['result'].get('error')}")

    warnings = [
        w for w in RUN_LOG["warnings"]
        if agent is None or w.startswith(f"[{agent}]")
    ]

    lines = ["Successful calculations / lookups:"]
    lines += ok or ["- none"]
    lines += ["Failed tool calls (these results do NOT exist):"]
    lines += failed or ["- none"]
    lines += ["Duplicate calls blocked:"]
    lines += blocked or ["- none"]
    lines += ["Validation and run warnings:"]
    lines += [f"- {w}" for w in warnings] or ["- none"]

    return "\n".join(lines)


