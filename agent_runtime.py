"""
Shared tool-calling loop, validation and run log for all specialist agents.
"""

import inspect
import json
import re

import ollama

import fact_ledger

MODEL = "llama3.2"
NUM_CTX = 8192
DIRECTOR_NUM_CTX = 16384
MAX_ITERATIONS = 6
MAX_REPAIRS = 2
MAX_STALLED_ROUNDS = 2

AUDIT_MARKER = "\n\n=== SYSTEM TOOL AUDIT (generated by code, not by the model) ==="

RUN_LOG = {
    "tool_calls": [],
    "iterations": [],
    "warnings": [],
    "corrected_warnings": [],
}


def start_run():
    for value in RUN_LOG.values():
        value.clear()


def chat(messages, tools=None, num_ctx=NUM_CTX):
    kwargs = {
        "model": MODEL,
        "messages": messages,
        "options": {"num_ctx": num_ctx},
    }

    if tools:
        kwargs["tools"] = tools

    return ollama.chat(**kwargs)


